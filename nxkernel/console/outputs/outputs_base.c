/* ===================== */
/* Font Access Function   */
/* ===================== */
const u8 *GetFont(char c)
{
    u8 uc = (u8)c;

    /* 범위 밖 문자는 공백 글리프로 대체 */
    if (uc < FONT_FIRST_CHAR || uc > FONT_LAST_CHAR)
        return FONTS[0];

    return FONTS[uc - FONT_FIRST_CHAR];
}

/* ===================== */
/* Fast Char Drawing      */
/* ===================== */

/*
 * (x, y) 를 좌상단으로 16x16 글자 하나를 그린다.
 * 주의: 범위 검사를 하지 않는다. 호출자가 (x+16, y+16) 이 프레임버퍼 안임을 보장해야 한다.
 */
Nstatus draw_char_fast(
    u32 *fb,
    u32  pixels_per_scanline,
    u32  x,
    u32  y,
    utf8 c,
    u32  fg,
    u32  bg
) {
    const u8 *glyph;
    u32 line_buffer[16]; /* 16px 폭 */
    u32 row;
    u32 bit;

    if (!fb || !pixels_per_scanline)
        return NinvalidArg;

    glyph = GetFont((char)c);

    for (row = 0; row < 16; row++) {
        u8 b0 = glyph[row * 2];
        u8 b1 = glyph[row * 2 + 1];

        /* 왼쪽 8픽셀 */
        for (bit = 0; bit < 8; bit++)
            line_buffer[bit] = (b0 & (0x80 >> bit)) ? fg : bg;

        /* 오른쪽 8픽셀 */
        for (bit = 0; bit < 8; bit++)
            line_buffer[8 + bit] = (b1 & (0x80 >> bit)) ? fg : bg;

        memcpy(
            &fb[(usize)(y + row) * pixels_per_scanline + x],
            line_buffer,
            sizeof(line_buffer)
        );
    }

    return NSTATUS_OK;
}

/*
 * 화면 크기(width x height)와 스캔라인 폭을 받아 경계를 검사한 뒤 그린다.
 * 글자 전체가 화면 안에 들어오지 않으면 아무것도 그리지 않고 NinvalidArg 를 반환한다.
 */
Nstatus draw_char_bounded(
    u32 *fb,
    u32  pixels_per_scanline,
    u32  width,
    u32  height,
    u32  x,
    u32  y,
    utf8 c,
    u32  fg,
    u32  bg
) {
    if (!fb || !pixels_per_scanline || pixels_per_scanline < width)
        return NinvalidArg;

    /* 뺄셈 전에 먼저 비교하여 u32 언더플로/오버플로를 원천 차단 */
    if (x > width || y > height)
        return NinvalidArg;
    if (width - x < FONT_WIDTH || height - y < FONT_HEIGHT)
        return NinvalidArg;

    return draw_char_fast(fb, pixels_per_scanline, x, y, c, fg, bg);
}
