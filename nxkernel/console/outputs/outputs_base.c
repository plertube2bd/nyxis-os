/* Fast Char Drawing      */
/* ===================== */

/* 16x16 비트맵 글자 하나 */
static void draw_bitmap_cell(u32 *fb, u32 pixels_per_scanline, u32 x, u32 y, utf8 c, u32 fg, u32 bg)
{
    const u8 *glyph;
    u32 line_buffer[16]; /* 16px 폭 */
    u32 row;
    u32 bit;

    glyph = GetFont((char)c);

    for (row = 0; row < 16; row++) {
        u8 b0 = glyph[row * 2];
        u8 b1 = glyph[row * 2 + 1];

        /* 왼쪽 8픽셀 */
        for (bit = 0; bit < 8; bit++)
            line_buffer[bit] = (b0 & (0x80 >> bit)) ? fg : bg;

        /* 오른쪽 8픽셀 */
        for (bit = 0; bit < 8; bit++)
            line_buffer[8 + bit] = (b1 & (0x80 >> bit)) ? fg : bg;

        memcpy(
            &fb[(usize)(y + row) * pixels_per_scanline + x],
            line_buffer,
            sizeof(line_buffer)
        );
    }
}

/*
 * (x, y) 를 좌상단으로 글자 셀 하나(font_cell_width() x font_cell_height())를 그린다.
 * 주의: 범위 검사를 하지 않는다. 호출자가 셀 전체가 프레임버퍼 안임을 보장해야 한다.
 */
Nstatus draw_char_fast(
    u32 *fb,
    u32  pixels_per_scanline,
    u32  x,
    u32  y,
    utf8 c,
    u32  fg,
    u32  bg
) {
    if (!fb || !pixels_per_scanline)
        return NinvalidArg;

#ifdef CONFIG_FONT_8x16
    if (g_use_ttf) {
        draw_ttf_cell(fb, pixels_per_scanline, x, y, c, fg, bg);
        return NSTATUS_OK;
    }
#endif
    draw_bitmap_cell(fb, pixels_per_scanline, x, y, c, fg, bg);
    return NSTATUS_OK;
}

/*
 * 화면 크기(width x height)와 스캔라인 폭을 받아 경계를 검사한 뒤 그린다.
 * 글자 셀 전체가 화면 안에 들어오지 않으면 아무것도 그리지 않고 NinvalidArg 를 반환한다.
 */
Nstatus draw_char_bounded(
    u32 *fb,
    u32  pixels_per_scanline,
    u32  width,
    u32  height,
    u32  x,
    u32  y,
    utf8 c,
    u32  fg,
    u32  bg
) {
    if (!fb || !pixels_per_scanline || pixels_per_scanline < width)
        return NinvalidArg;

    /* 뺄셈 전에 먼저 비교하여 u32 언더플로/오버플로를 원천 차단 */
    if (x > width || y > height)
        return NinvalidArg;
    if (width - x < font_cell_width() || height - y < font_cell_height())
        return NinvalidArg;

    return draw_char_fast(fb, pixels_per_scanline, x, y, c, fg, bg);
}

/*
 * 글꼴을 알파 비트맵으로 내보낸다 (dev:/console 의 NX_DEVCMD_CONSOLE_FONT).
 * 글자 FONT_FIRST_CHAR..FONT_LAST_CHAR 를 차례로, 글자마다 셀 폭 x 셀 높이 바이트 (0 = 배경, 255 = 글자색).
 * 필요한 바이트 수를 돌려준다. out 이 NULL 이거나 cap 이 모자라면 쓰지 않는다.
 */
usize font_export(u8 *out, usize cap)
{
    u32 w = font_cell_width();
    u32 h = font_cell_height();
    usize need = (usize)FONT_CHAR_COUNT * w * h;
    u32 i;

    if (!out || cap < need)
        return need;
#ifdef CONFIG_FONT_8x16
    if (g_use_ttf) {
        memcpy(out, g_ttf_glyphs, need);
        return need;
    }
#endif
    for (i = 0; i < FONT_CHAR_COUNT; i++) {
        const u8 *glyph = FONTS[i];
        u8 *dst = out + (usize)i * w * h;
        u32 row;
        u32 bit;

        for (row = 0; row < 16U; row++) {
            for (bit = 0; bit < 16U; bit++) {
                u8 b = glyph[row * 2U + bit / 8U];

                dst[row * 16U + bit] = (b & (0x80U >> (bit % 8U))) ? 255U : 0U;
            }
        }
    }
    return need;
}
