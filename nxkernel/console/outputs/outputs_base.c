/* Font Access Function   */
/* ===================== */
const u8 *GetFont(char c)
{
    u8 uc = (u8)c;

    /* 범위 밖 문자는 공백 글리프로 대체 */
    if (uc < FONT_FIRST_CHAR || uc > FONT_LAST_CHAR)
        return FONTS[0];

    return FONTS[uc - FONT_FIRST_CHAR];
}

