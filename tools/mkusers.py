#!/usr/bin/env python3
"""
mkusers.py - NyxisOS 사용자 DB(roi:/users) 생성

  make users                 (= python3 tools/mkusers.py config/users.db)
      계정과 비밀번호를 터미널에서 묻는다 (비밀번호는 화면에 나오지 않는다).
      결과 파일에는 솔트와 PBKDF2-HMAC-SHA256 해시만 들어간다 (평문 비밀번호는 어디에도 저장하지 않는다).
      config/ 는 git 이 추적하지 않는다.

  python3 tools/mkusers.py --test <db> <password-file>
      자체 점검 이미지용: root(uid 0)와 test(uid 1000)를 무작위 비밀번호로 만든다.
      비밀번호는 <password-file> 에 "이름:비밀번호" 로 남긴다 (테스트 하네스가 읽는다). 이 계정들은
      SELFTEST 이미지에만 들어간다.

DB 형식 (커널 kernel/security/auth.h 와 같음):  이름:uid:gid:반복횟수:솔트hex:해시hex
"""
import getpass
import hashlib
import os
import re
import secrets
import sys

ITERATIONS = 100000         # 커널 auth.c 의 허용 범위: 1000 ~ 1000000 (QEMU 에서 로그인 한 번에 약 0.3초)
TEST_ITERATIONS = 2000      # 테스트 이미지는 부팅/테스트 시간을 줄이려고 낮춘다
NAME_RE = re.compile(r"^[a-z0-9_-]{1,31}$")


def entry(name, uid, gid, password, iterations):
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, iterations, 32)
    return f"{name}:{uid}:{gid}:{iterations}:{salt.hex()}:{digest.hex()}\n"


def write_db(path, lines):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write("# NyxisOS user database (roi:/users) - generated by tools/mkusers.py\n")
        f.write("# name:uid:gid:iterations:salt:pbkdf2-hmac-sha256\n")
        f.writelines(lines)
    total = sum(len(l) for l in lines) + 120
    if total > 4000:
        print(f"warning: {path} is {total} bytes; the kernel reads at most 4095", file=sys.stderr)


def interactive(path):
    if not sys.stdin.isatty():
        sys.exit("make users needs a terminal (passwords are read without echo)")
    print("NyxisOS accounts. Leave the name empty to finish.")
    print("Tip: create 'root' (uid 0) so you can log in as the administrator.")
    lines, names, uids = [], set(), set()
    while True:
        name = input("user name: ").strip()
        if not name:
            break
        if not NAME_RE.match(name) or name in names:
            print("  invalid or duplicate name (a-z 0-9 _ -, up to 31 chars)")
            continue
        default_uid = 0 if name == "root" else max([999] + [u for u in uids if u >= 1000]) + 1
        raw = input(f"  uid [{default_uid}]: ").strip()
        uid = int(raw) if raw else default_uid
        if uid in uids or not 0 <= uid < 2**31:
            print("  invalid or duplicate uid")
            continue
        raw = input(f"  gid [{uid}]: ").strip()
        gid = int(raw) if raw else uid
        while True:
            pw = getpass.getpass("  password: ")
            if len(pw) < 4 or len(pw) > 128:
                print("  password must be 4..128 characters")
                continue
            if getpass.getpass("  again: ") != pw:
                print("  passwords do not match")
                continue
            break
        lines.append(entry(name, uid, gid, pw, ITERATIONS))
        names.add(name)
        uids.add(uid)
        pw = None
    if not lines:
        sys.exit("no users entered; nothing written")
    write_db(path, lines)
    print(f"wrote {path} ({len(lines)} user(s)). Rebuild the image: make os")


def test_db(path, pwfile):
    users = [("root", 0, 0), ("test", 1000, 1000)]
    lines, creds = [], []
    for name, uid, gid in users:
        pw = secrets.token_urlsafe(12)
        lines.append(entry(name, uid, gid, pw, TEST_ITERATIONS))
        creds.append(f"{name}:{pw}\n")
    write_db(path, lines)
    fd = os.open(pwfile, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.writelines(creds)


def main():
    args = sys.argv[1:]
    if len(args) == 3 and args[0] == "--test":
        test_db(args[1], args[2])
    elif len(args) == 1 and not args[0].startswith("-"):
        interactive(args[0])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
